def require_jwt(f):
    """Middleware decorator that enforces JWT authentication."""
    @wraps(f)
    def decorated(*args, **kwargs):
        auth_header = request.headers.get("Authorization", "")
        if not auth_header.startswith("Bearer "):
            return jsonify({"error": "Missing or malformed Authorization header"}), 401

        token   = auth_header.split(" ", 1)[1]
        payload = vulnerable_decode_jwt(token)

        if payload is None:
            return jsonify({"error": "Invalid or expired token"}), 401

        request.jwt_payload = payload
        return f(*args, **kwargs)

    return decorated


def require_admin(f):
    """Middleware decorator that enforces admin role."""
    @wraps(f)
    @require_jwt
    def decorated(*args, **kwargs):
        role = request.jwt_payload.get("role", "user")
        if role != "admin":
            return jsonify({"error": "Admin access required", "your_role": role}), 403
        return f(*args, **kwargs)

    return decorated


