@app.route("/login", methods=["POST"])
def login():
    """
    Login endpoint — issues JWT tokens.

    POST body (JSON):
      { "username": "alice", "password": "password123", "alg": "HS256" }

    The 'alg' field lets the client choose HS256 or RS256.
    VULNERABILITY: In production, the server should always decide the algorithm.
    """
    data = request.get_json(silent=True) or {}

    username = data.get("username", "")
    password = data.get("password", "")
    alg      = data.get("alg", "HS256").upper()

    # Check credentials
    user = USERS.get(username)
    if not user or user["password"] != password:
        return jsonify({"error": "Invalid credentials"}), 401

    # Build JWT payload
    now     = datetime.utcnow()
    payload = {
        "sub":      username,
        "role":     user["role"],
        "iat":      now,
        "exp":      now + timedelta(hours=1),
        "iss":      "jwt-lab",
    }

    # Issue token with requested algorithm
    if alg == "RS256":
        token = jwt.encode(payload, PRIVATE_KEY, algorithm="RS256")
    else:
        # Default: HS256
        token = jwt.encode(payload, HS256_SECRET, algorithm="HS256")

    return jsonify({
        "token":     token,
        "algorithm": alg,
        "username":  username,
        "role":      user["role"],
        "expires_in": "1 hour",
    })


