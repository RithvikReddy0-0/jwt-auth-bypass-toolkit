def vulnerable_decode_jwt(token: str) -> dict | None:
    """
    VULNERABILITY: This function reads the 'alg' field from the JWT header
    WITHOUT verifying it against an allowed algorithm list.

    Attack surface:
      - alg=none   → signature skipped entirely
      - alg=HS256  → attacker uses the PUBLIC key as HMAC secret (RS256→HS256 confusion)
      - alg=RS256  → verified normally

    A secure implementation MUST specify algorithms= explicitly and NEVER
    trust the header's alg claim.
    """
    try:
        # Decode header without verification to see which alg was used
        header = jwt.get_unverified_header(token)
        alg    = header.get("alg", "").upper()

        if alg == "NONE":
            # ❌ VULNERABILITY 1: alg=none bypass
            # PyJWT by default rejects none, but we're calling it with options=
            # that disable signature verification — simulating a broken implementation.
            payload = jwt.decode(
                token,
                options={
                    "verify_signature": False,  # ← DANGEROUS
                    "verify_exp": True,
                },
                algorithms=["none"],
            )
            return payload

        elif alg == "HS256":
            # ❌ VULNERABILITY 2: RS256→HS256 confusion
            # A vulnerable implementation uses the PUBLIC key as the HMAC secret.
            # We simulate this by manually verifying the HMAC rather than relying
            # on PyJWT (which added a safeguard against this exact pattern in >= 2.4).
            #
            # Real-world vulnerable libraries (node-jsonwebtoken < 4.2.2, python-jose < 3.x)
            # simply passed public_key_pem directly as the HS256 secret.
            import hmac as _hmac
            import hashlib as _hashlib

            parts = token.split(".")
            if len(parts) != 3:
                return None

            signing_input = f"{parts[0]}.{parts[1]}".encode("utf-8")
            import base64 as _base64

            def _b64d(s):
                s += "=" * (4 - len(s) % 4)
                return _base64.urlsafe_b64decode(s)

            expected_sig = _hmac.new(
                key=PUBLIC_KEY_PEM,          # ← public key as HMAC secret (the vulnerability!)
                msg=signing_input,
                digestmod=_hashlib.sha256,
            ).digest()

            provided_sig = _b64d(parts[2])

            if not _hmac.compare_digest(expected_sig, provided_sig):
                return None

            # Signature matched — decode payload (this is what the vulnerable server does)
            payload_json = _b64d(parts[1])
            import json as _json
            return _json.loads(payload_json)

        elif alg == "RS256":
            # Legitimate RS256 verification (correct behavior)
            payload = jwt.decode(
                token,
                key=PUBLIC_KEY,
                algorithms=["RS256"],
            )
            return payload

        else:
            return None

    except jwt.ExpiredSignatureError:
        return None
    except jwt.InvalidTokenError:
        return None


